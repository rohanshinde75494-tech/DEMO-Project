public class AUTOBOXING {
    public static void main(String[] args) {
        int x=10;  //AUTOBOXING
        Integer y=x;
        System.out.println(x);
        System.out.println(y); //unboxing

        Integer a=20;     //autoboxing
        int b=a;                  //unboxing
        System.out.println(a);
        System.out.println(b);
    }
}
